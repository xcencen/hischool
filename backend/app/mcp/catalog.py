"""Static schemas shared by the issuer, MCP server and trusted client."""

from dataclasses import dataclass
from datetime import date
import re
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field, StringConstraints, field_validator, model_validator


PositiveId = Annotated[int, Field(strict=True, ge=1)]
ShortText = Annotated[str, StringConstraints(strict=True, strip_whitespace=True, max_length=100)]


class StrictModel(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)


class ScheduleArguments(StrictModel):
    date: Annotated[str, StringConstraints(strict=True, min_length=1, max_length=10)] = "today"

    @field_validator("date")
    @classmethod
    def valid_date(cls, value):
        if value not in {"today", "tomorrow", "this_week"}:
            if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", value):
                raise ValueError("Use today, tomorrow, this_week or an ISO date")
            parsed = date.fromisoformat(value)
            if not 2000 <= parsed.year <= 2100:
                raise ValueError("Date is outside the supported range")
        return value


