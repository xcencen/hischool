@dataclass(frozen=True)
class ToolSpec:
    description: str
    arguments: type[BaseModel]
    result: type[BaseModel]


TOOLS = {
    "campus_get_my_schedules": ToolSpec("查询本人今日、明日、本周或指定日期课表；身份由服务端注入。", ScheduleArguments, ScheduleData),
    "campus_list_notices": ToolSpec("分页查询已发布且分类有效的校园通知。", NoticeListArguments, NoticeListData),
    "campus_get_notice": ToolSpec("按通知编号查询已发布通知详情。", NoticeArguments, NoticeData),
    "campus_list_activities": ToolSpec("分页查询已发布校园活动。", ActivityListArguments, ActivityListData),
    "campus_get_activity": ToolSpec("查询已发布活动详情及本人报名状态，只读。", ActivityArguments, ActivityData),
    "campus_search_knowledge": ToolSpec("检索校园手册原文片段，保留文档版本、章节和页码。", KnowledgeArguments, KnowledgeData),
}


class ToolOutcome(StrictModel):
    version: Literal[1] = 1
    tool: str
    run_id: str | None = None
    ok: Annotated[bool, Field(strict=True)]
    data: dict | None = None
    citations: Annotated[list[Citation], Field(max_length=50)] = []
    reason: Literal["unauthenticated", "forbidden", "invalid_arguments", "unknown_tool",
                    "not_found", "rate_limited", "timeout", "unavailable", "invalid_response"] | None = None
    retryable: Annotated[bool, Field(strict=True)] = False
    observed_at: Annotated[str, Field(max_length=40)]

    @model_validator(mode="after")
    def valid_result(self):
        if self.tool not in TOOLS and not (self.tool == "unknown" and not self.ok):
            raise ValueError("Unexpected tool result")
        if self.ok:
            if self.reason is not None or self.data is None or self.retryable:
                raise ValueError("Invalid success envelope")
            self.data = TOOLS[self.tool].result.model_validate(self.data).model_dump(mode="json")
        elif self.reason is None or self.data is not None or self.citations:
            raise ValueError("Failure must contain no business data")
        return self
