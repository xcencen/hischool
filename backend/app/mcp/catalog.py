class Citation(StrictModel):
    source_id: Annotated[str, Field(pattern=r"^S[1-9][0-9]?$", max_length=3)]
    kind: Literal["schedule", "notice", "activity", "knowledge"]
    item_id: PositiveId
    title: Annotated[str, Field(max_length=150)]
    url: Annotated[str, Field(max_length=200)]
    version: PositiveId | None = None
    page_number: PositiveId | None = None
    page_label: Annotated[str, Field(max_length=40)] | None = None
    chapter: Annotated[str, Field(max_length=500)] | None = None
    chunk_id: PositiveId | None = None

    @model_validator(mode="after")
    def trusted_link(self):
        paths = {"schedule": "/app/schedule", "notice": f"/app/notices/{self.item_id}",
                 "activity": f"/app/activities/{self.item_id}"}
        if self.kind == "knowledge":
            if self.version is None or self.page_number is None or self.chunk_id is None:
                raise ValueError("Knowledge citation must identify a version and page")
            expected = (f"/api/knowledge/documents/{self.item_id}/source?version={self.version}"
                        f"#page={self.page_number}")
        else:
            expected = paths[self.kind]
        if self.url != expected:
            raise ValueError("Citation link must be generated by the campus service")
        return self


